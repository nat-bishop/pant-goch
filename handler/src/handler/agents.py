"""LLM agents — two agents per HANDLER_SPEC_V2 §8.

- `DRAFTER_AGENT` — produces 3–4 candidate options per cycle, structured
  `OptionSet` output, Operations voice. **Stateless one-shot** — each call
  is a fresh prompt with no `message_history`.
- `LOG_WRITER_AGENT` — appends the cycle's case-file entry after effects
  apply, Operations voice (str output, streamed). **Conversation-based** —
  one pydantic-ai agent per session whose `message_history` accumulates
  one user+assistant pair per cycle. The conversation IS the case file.
  After each entry, a non-persisted shorthand call runs against the same
  agent + history to produce the history-row one-liner.

Why the split (HANDLER_SPEC_V2 §8.4): the drafter's job is per-cycle
enumeration — prior assistant turns would just be stale option sets the
model would feel obliged to vary or echo. The log writer's job is keeping
a coherent case-file voice — multi-turn coherence works because every
entry is the same Operations register.

Prompt structure (KV-cache friendly per §8.4):
  Drafter:    [stable system prompt] + [dynamic user prompt]
  Log writer: [stable system prompt] + [accumulating message_history]

The system prompts are baked at `build_agent_bundle(model, mission)` time —
once per mission load. User prompts are built per call by
`_drafter_user_prompt`, `_log_writer_user_prompt`, `_shorthand_user_prompt`.

This module has NO direct LLM call sites. `cycle.py` wraps the agent runs
into the `DrafterFn`/`LogWriterFn` protocols; `main.py` wires up the paced
word-stream emitter and the persistent log message-history.
"""
